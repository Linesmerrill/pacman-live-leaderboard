const GLYPH_W = 5;
const GLYPH_H = 7;
const SPACING = 1;
const SVG_NS = 'http://www.w3.org/2000/svg';
const pathCache = new Map();

/** SVG path data for `text`, merging horizontal runs of pixels to keep paths small. */
export function pixelPath(text) {
  const key = String(text).toUpperCase();
  const cached = pathCache.get(key);
  if (cached) return cached;
  let d = '';
  let x = 0;
  for (const ch of key) {
    const glyph = G[ch] ?? G['?'];
    for (let row = 0; row < GLYPH_H; row++) {
      const line = glyph[row];
      for (let col = 0; col < GLYPH_W; ) {
        if (line[col] !== '#') {
          col++;
          continue;
        }
        let run = 1;
        while (col + run < GLYPH_W && line[col + run] === '#') run++;
        d += `M${x + col} ${row}h${run}v1h-${run}z`;
        col += run;
      }
    }
    x += GLYPH_W + SPACING;
  }
  const result = { d, width: Math.max(1, x - SPACING) };
  pathCache.set(key, result);
  return result;
}

/** Width of `text` in font pixels (multiply by the font-size to get CSS size). */
export function pixelWidth(text) {
  return pixelPath(text).width;
}

/** An inline <svg> showing `text` in the pixel font, colored by CSS `color`. */
export function pixelText(text, className = '') {
  const { d, width } = pixelPath(text);
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', `0 0 ${width} ${GLYPH_H}`);
  svg.setAttribute('class', `px ${className}`.trim());
  svg.setAttribute('role', 'img');
  svg.setAttribute('aria-label', String(text));
  svg.setAttribute('shape-rendering', 'crispEdges');
  svg.style.width = `${width}em`;
  svg.style.height = `${GLYPH_H}em`;
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('d', d);
  path.setAttribute('fill', 'currentColor');
  svg.append(path);
  return svg;
}
